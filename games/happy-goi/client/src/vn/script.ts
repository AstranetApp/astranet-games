export const pick = (scenes: Scene[]) => scenes[Math.floor(Math.random() * scenes.length)];

/** Сцена после подрыва: сначала игрока собирают, и только потом шутят. */
export const lossScene = (): Scene => [...pick(CHESTER_LINES), ...pick(LOSS_LINES)];

export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) =>
    k in vars ? String(vars[k]) : m);
}
